  private showResourceTree(
    map: Map<string, Resource>,
    prefix: string,
    transpiled = false,
  ) {
    const resources = Array.from(map.entries())
    resources.forEach(([name, resource], index) => {
      const isLast = index === resources.length - 1
      const hasChildren =
        resource.children && resource.children.size > 0 ? true : false
      const currentPrefix = isLast ? '└── ' : '├── '
      const nextPrefix = isLast ? '    ' : '│   '

      const formatParentheses = (length: number) => {
        switch (length) {
          case 0:
            return '(barrel)'
          case 1:
            return `(1 ${transpiled ? 'type' : 'method'})`
          default:
            return `(${length} ${transpiled ? 'types' : 'methods'})`
        }
      }

      this.logger.log(`${prefix}${currentPrefix}${name}/`)
      this.logger.log(
        `${prefix}${nextPrefix}${hasChildren ? '├── ' : '└── '}index${transpiled ? '.d.ts' : '.ts'} ${formatParentheses(resource.methods.length)}`,
      )

      if (hasChildren)
        this.showResourceTree(
          resource.children!,
          `${prefix}${nextPrefix}`,
          transpiled,
        )
    })
  }

  private showFinalOutputTree(map: Map<string, Resource>, prefix: string) {
    const resources = Array.from(map.entries())
    resources.forEach(([name, resource], index) => {
      const isLast = index === resources.length - 1
      const hasChildren =
        resource.children != null && resource.children.size > 0
      const currentPrefix = isLast ? '└── ' : '├── '
      const nextPrefix = isLast ? '    ' : '│   '

      this.logger.log(`${prefix}${currentPrefix}${name}/`)
      this.logger.log(`${prefix}${nextPrefix}├── index.js`)
      this.logger.log(`${prefix}${nextPrefix}└── index.d.ts`)

      if (hasChildren)
        this.showFinalOutputTree(resource.children!, `${prefix}${nextPrefix}`)
    })
  }

